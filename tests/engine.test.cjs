const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { compareDirectories, planCopy, executeCopy, safePath, validateRoots } = require('../dist/engine.js')
async function fixture(t) {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'dirdelta-test-')))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const left = path.join(root, 'left'), right = path.join(root, 'right')
  await fs.mkdir(left); await fs.mkdir(right)
  return { root, left, right, signal: new AbortController().signal }
}
test('fast mode reports missing, unverified, different sizes, empty directories and type conflicts', async t => {
  const f = await fixture(t)
  await fs.writeFile(path.join(f.left, '.hidden'), 'hidden')
  await fs.mkdir(path.join(f.left, 'empty'))
  await fs.writeFile(path.join(f.right, 'right.txt'), 'right')
  await fs.writeFile(path.join(f.left, 'same-size'), 'aaa')
  await fs.writeFile(path.join(f.right, 'same-size'), 'bbb')
  await fs.writeFile(path.join(f.left, 'size'), 'a')
  await fs.writeFile(path.join(f.right, 'size'), 'bb')
  await fs.mkdir(path.join(f.left, 'conflict'))
  await fs.writeFile(path.join(f.right, 'conflict'), 'file')
  const result = await compareDirectories(f.left, f.right, false, f.signal)
  const statuses = Object.fromEntries(result.rows.map(r => [r.path, r.status]))
  assert.equal(statuses['.hidden'], 'left-only'); assert.equal(statuses.empty, 'left-only')
  assert.equal(statuses['right.txt'], 'right-only'); assert.equal(statuses['same-size'], 'unchecked')
  assert.equal(statuses.size, 'different'); assert.equal(statuses.conflict, 'conflict')
  await assert.rejects(planCopy(result, 'left', ['conflict']), /çakışması/)
})
test('SHA-256 detects same-sized content differences and identifies equal content', async t => {
  const f = await fixture(t)
  for (const side of [f.left, f.right]) await fs.writeFile(path.join(side, 'equal'), 'equal')
  await fs.writeFile(path.join(f.left, 'different'), 'aaa')
  await fs.writeFile(path.join(f.right, 'different'), 'bbb')
  const result = await compareDirectories(f.left, f.right, true, f.signal)
  assert.equal(result.rows.find(r => r.path === 'different').status, 'different')
  assert.equal(result.rows.find(r => r.path === 'equal').status, 'same')
  assert.equal(result.rows[0].left.hash.length, 64)
})
test('copies nested directories and empty directories, verifies hashes, then compares equal', async t => {
  const f = await fixture(t)
  await fs.mkdir(path.join(f.left, 'nested/empty'), { recursive: true })
  await fs.writeFile(path.join(f.left, 'nested/file'), 'content')
  const result = await compareDirectories(f.left, f.right, true, f.signal)
  const plan = await planCopy(result, 'left', ['nested'])
  assert.equal(await executeCopy(result, 'left', plan, false, f.signal), 3)
  assert.equal(await fs.readFile(path.join(f.right, 'nested/file'), 'utf8'), 'content')
  const after = await compareDirectories(f.left, f.right, true, f.signal)
  assert.ok(after.rows.every(row => row.status === 'same'))
})
test('never overwrites without approval and supports approved replacement', async t => {
  const f = await fixture(t)
  await fs.writeFile(path.join(f.left, 'file'), 'new')
  await fs.writeFile(path.join(f.right, 'file'), 'old')
  const result = await compareDirectories(f.left, f.right, true, f.signal)
  const plan = await planCopy(result, 'left', ['file'])
  await assert.rejects(executeCopy(result, 'left', plan, false, f.signal), { code: 'EEXIST' })
  assert.equal(await fs.readFile(path.join(f.right, 'file'), 'utf8'), 'old')
  await executeCopy(result, 'left', plan, true, f.signal)
  assert.equal(await fs.readFile(path.join(f.right, 'file'), 'utf8'), 'new')
  assert.deepEqual(await fs.readdir(f.right), ['file'])
})
test('rejects nested roots, traversal and symlink writes, and skips symlinks during scan', async t => {
  const f = await fixture(t)
  await fs.mkdir(path.join(f.left, 'nested'))
  await assert.rejects(validateRoots(f.left, path.join(f.left, 'nested')), /iç içe/)
  await assert.rejects(validateRoots(f.left, f.left), /Aynı/)
  await assert.rejects(safePath(f.left, '../escape'), /Geçersiz/)
  await fs.symlink(f.right, path.join(f.left, 'link'), 'dir')
  await assert.rejects(safePath(f.left, 'link/file'), /Sembolik/)
  const result = await compareDirectories(f.left, f.right, false, f.signal)
  assert.equal(result.warnings.length, 1)
  assert.ok(!result.rows.some(r => r.path === 'link'))
})
test('cancellation stops scanning and copying without leaving temporary files', async t => {
  const f = await fixture(t)
  await fs.writeFile(path.join(f.left, 'file'), 'content')
  const result = await compareDirectories(f.left, f.right, true, f.signal)
  const plan = await planCopy(result, 'left', ['file'])
  const controller = new AbortController(); controller.abort()
  await assert.rejects(compareDirectories(f.left, f.right, true, controller.signal), { name: 'AbortError' })
  await assert.rejects(executeCopy(result, 'left', plan, false, controller.signal), { name: 'AbortError' })
  assert.deepEqual(await fs.readdir(f.right), [])
})
test('rejects source changes made after planning', async t => {
  const f = await fixture(t)
  await fs.writeFile(path.join(f.left, 'file'), 'original')
  const result = await compareDirectories(f.left, f.right, false, f.signal)
  const plan = await planCopy(result, 'left', ['file'])
  await fs.writeFile(path.join(f.left, 'file'), 'changed content')
  await assert.rejects(executeCopy(result, 'left', plan, false, f.signal), /Kaynak değişti/)
  assert.deepEqual(await fs.readdir(f.right), [])
})
